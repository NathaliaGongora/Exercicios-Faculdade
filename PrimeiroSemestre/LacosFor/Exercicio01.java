package PrimeiroSemestre.LacosFor;

public class Exercicio01 {

    public static void main(String[] args) {

        System.out.println("Numeros pares de 1 a 10: ");

        for (int i = 1; i <= 10; i++) {

            if (i % 2 == 0) {

                System.out.println(i);
            }
        }
    }
}
